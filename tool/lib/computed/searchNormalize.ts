/**
 * 日本語フリーテキスト検索向けの正規化ヘルパー。
 *
 * 100 人規模運用で「タナカで検索しても furigana が "たなか" だとヒットしない」
 * 「ＡＢＣ社 (全角) が abc社 と区別される」といった「実用上ヒットしない」事故を
 * 防ぐため、検索クエリと検索対象の両方を同じ正規化に通してから比較する。
 *
 * 正規化ルール:
 *   1. NFKC: 全角英数 → 半角、半角カタカナ → 全角カタカナ、合成済み濁点も統合
 *   2. toLowerCase: 大文字小文字を畳む (英字)
 *   3. カタカナ → ひらがな (U+30A1〜U+30F6 を -0x60 シフト)
 *
 * 上記により以下が同一視される:
 *   - "ＴＡＮＡＫＡ" / "TANAKA" / "tanaka"
 *   - "タナカ" / "たなか"
 *   - "ｶﾀｶﾅ" / "カタカナ" / "かたかな"
 *
 * 注意: 「ヴ」「ゔ」のような濁点合成は NFKC で正規化済み。「ｦ」(半角を) は
 * 「を」へ落ちる。
 */
export function normalizeForSearch(s: string): string {
  return s
    .normalize("NFKC")
    .toLowerCase()
    .replace(/[ァ-ヶ]/g, (m) =>
      String.fromCharCode(m.charCodeAt(0) - 0x60),
    );
}
